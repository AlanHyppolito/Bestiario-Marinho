SELECT 
    h.data_hora AS data,
    h.hora AS hora,
    b.nome AS besta,
    u.nome AS usuario
FROM historico h
JOIN bestas b 
    ON h.fk_besta = b.id_besta
JOIN users u 
    ON h.fk_usuario = u.id
ORDER BY h.data_hora, h.hora;

