FROM historico h
JOIN bestas b ON h.fk_besta = b.id_besta
JOIN users u ON h.fk_usuario = u.id
WHERE u.id = 1 and h.dia >= curdate() - interval 15 day
ORDER BY h.dia DESC, h.hora DESC;